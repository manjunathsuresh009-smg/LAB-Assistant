import { Prisma } from "@prisma/client";
import { config } from "../config";
import { prisma } from "../prisma";
import { serializeEquipment } from "../utils/serializers";
import { rankEquipment } from "./recommendation";

type EquipmentRow = Prisma.EquipmentGetPayload<{ include: { department: true } }>;

export interface AiRecommendationItem {
  equipment: ReturnType<typeof serializeEquipment>;
  reason: string;
  confidence: number;
  matchedKeywords: string[];
}

export interface AiRecommendationResult {
  source: "gemini" | "rule-based";
  summary: string;
  note: string;
  generatedAt: Date;
  recommendations: AiRecommendationItem[];
}

function ruleBasedResult(description: string, rows: EquipmentRow[], note: string): AiRecommendationResult {
  const ranked = rankEquipment(description, rows, 5);
  const byId = new Map(rows.map((item) => [item.id, item]));
  const recommendations = ranked
    .filter((item) => byId.has(item.equipmentId))
    .map((item) => ({
      equipment: serializeEquipment(byId.get(item.equipmentId)!),
      reason: item.reason,
      confidence: Math.round(item.confidence),
      matchedKeywords: item.matchedKeywords,
    }));

  const names = recommendations.map((item) => item.equipment.name).slice(0, 3);
  const summary = names.length
    ? `Deterministic keyword match across the lab catalogue suggests ${names.join(", ")} for this project.`
    : "No catalogue resource matched strongly. Start with a general prototyping kit and refine the brief.";

  return { source: "rule-based", summary, note, generatedAt: new Date(), recommendations };
}

function extractJson(text: string): unknown {
  const cleaned = text.replace(/```json/gi, "").replace(/```/g, "").trim();
  const firstBrace = cleaned.indexOf("{");
  const lastBrace = cleaned.lastIndexOf("}");
  const candidate =
    firstBrace >= 0 && lastBrace > firstBrace ? cleaned.slice(firstBrace, lastBrace + 1) : cleaned;
  return JSON.parse(candidate);
}

async function geminiRecommend(
  description: string,
  rows: EquipmentRow[]
): Promise<AiRecommendationResult | null> {
  if (!config.geminiApiKey) return null;

  const catalog = rows.map((item) => ({
    id: item.id,
    name: item.name,
    category: item.category,
    description: item.description,
    tags: item.tags,
    quantity: item.quantity,
  }));

  const prompt = [
    "You are CampusLab AI, a laboratory resource advisor for a university.",
    "Recommend 3 to 5 pieces of equipment from the CATALOG only. Never invent equipment.",
    "For each, explain concretely why the student's project needs it.",
    "Return STRICT JSON with this shape:",
    '{"summary":"one sentence","recommendations":[{"equipmentId":"id","reason":"why"}]}',
    `CATALOG: ${JSON.stringify(catalog)}`,
    `PROJECT: ${description}`,
  ].join("\n");

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 12_000);
  try {
    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/${config.geminiModel}:generateContent?key=${config.geminiApiKey}`,
      {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        signal: controller.signal,
        body: JSON.stringify({
          contents: [{ role: "user", parts: [{ text: prompt }] }],
          generationConfig: { temperature: 0.2, responseMimeType: "application/json" },
        }),
      }
    );
    if (!response.ok) return null;
    const payload = (await response.json()) as {
      candidates?: Array<{ content?: { parts?: Array<{ text?: string }> } }>;
    };
    const text =
      payload.candidates?.[0]?.content?.parts?.map((part) => part.text ?? "").join("") ?? "";
    if (!text) return null;

    const parsed = extractJson(text) as {
      summary?: string;
      recommendations?: Array<{ equipmentId?: string; reason?: string }>;
    };
    const byId = new Map(rows.map((item) => [item.id, item]));

    const items: AiRecommendationItem[] = [];
    for (const rec of parsed.recommendations ?? []) {
      const match = rec.equipmentId ? byId.get(rec.equipmentId) : undefined;
      if (!match || items.some((item) => item.equipment.id === match.id)) continue;
      items.push({
        equipment: serializeEquipment(match),
        reason: rec.reason?.trim() || "Recommended by Gemini for this project.",
        confidence: 90,
        matchedKeywords: [],
      });
      if (items.length >= 5) break;
    }

    if (!items.length) return null;

    return {
      source: "gemini",
      summary:
        parsed.summary?.trim() || "Gemini identified the following lab resources for your project.",
      note: `Generated by Gemini (${config.geminiModel}) using the live equipment catalogue.`,
      generatedAt: new Date(),
      recommendations: items,
    };
  } catch {
    return null;
  } finally {
    clearTimeout(timeout);
  }
}

export async function recommendEquipment(description: string): Promise<AiRecommendationResult> {
  const rows = await prisma.equipment.findMany({
    where: { status: "AVAILABLE" },
    include: { department: true },
    orderBy: { name: "asc" },
  });

  const gemini = await geminiRecommend(description, rows);
  if (gemini) return gemini;

  const note = config.geminiApiKey
    ? "Gemini could not be reached, so these results come from the deterministic rule-based engine (not an LLM)."
    : "No Gemini API key is configured. These results come from the deterministic rule-based engine (not an LLM).";

  return ruleBasedResult(description, rows, note);
}
